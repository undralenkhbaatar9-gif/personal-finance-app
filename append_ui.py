with open('finance/ui.py', 'a', encoding='utf-8') as f:
    f.write('\n\n')
    f.write('def render_lang_toggle(location: str = "sidebar") -> str:\n')
    f.write('    """Simple language toggle."""\n')
    f.write('    try:\n')
    f.write('        import streamlit as st\n')
    f.write('    except Exception:\n')
    f.write('        return "mn"\n')
    f.write('    if not hasattr(st, "session_state"):\n')
    f.write('        return "mn"\n')
    f.write('    if "lang" not in st.session_state:\n')
    f.write('        st.session_state["lang"] = "mn"\n')
    f.write('    lang = st.session_state["lang"]\n')
    f.write('    try:\n')
    f.write('        if location in ("sidebar", "side", "left"):\n')
    f.write('            with st.sidebar:\n')
    f.write('                st.markdown("**Хэл / Language**")\n')
    f.write('                c1, c2 = st.columns(2)\n')
    f.write('                with c1:\n')
    f.write('                    if st.button("MN", use_container_width=True, type="primary" if lang == "mn" else "secondary", key="lt_mn_sb"):\n')
    f.write('                        st.session_state["lang"] = "mn"\n')
    f.write('                        st.rerun()\n')
    f.write('                with c2:\n')
    f.write('                    if st.button("EN", use_container_width=True, type="primary" if lang == "en" else "secondary", key="lt_en_sb"):\n')
    f.write('                        st.session_state["lang"] = "en"\n')
    f.write('                        st.rerun()\n')
    f.write('            return st.session_state["lang"]\n')
    f.write('    except Exception:\n')
    f.write('        pass\n')
    f.write('    try:\n')
    f.write('        c1, c2, c3 = st.columns([8, 1, 1])\n')
    f.write('        with c2:\n')
    f.write('            if st.button("MN", use_container_width=True, type="primary" if st.session_state.get("lang") == "mn" else "secondary", key="lt_mn_top"):\n')
    f.write('                st.session_state["lang"] = "mn"\n')
    f.write('                st.rerun()\n')
    f.write('        with c3:\n')
    f.write('            if st.button("EN", use_container_width=True, type="primary" if st.session_state.get("lang") == "en" else "secondary", key="lt_en_top"):\n')
    f.write('                st.session_state["lang"] = "en"\n')
    f.write('                st.rerun()\n')
    f.write('    except Exception:\n')
    f.write('        pass\n')
    f.write('    return st.session_state.get("lang", "mn")\n')
print('done')
